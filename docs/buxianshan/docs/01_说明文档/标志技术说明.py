标志技术说明 = """
不咸山标志的技术来源与维护说明。

一、标志的原始来源

不咸山标志最初不是手写的字符画，而是来自一张 PNG 像素图片。

原始图片路径：
/data/data/com.termux/files/home/myproject/turtle_16.png

这是一张 16x16 像素的彩色像素画。
图像中包含龟壳、身体、眼睛、爪子等细节。

后来这张 PNG 图片经过 Python 脚本转换，
变成了现在项目里的 标志.py。

转换完成之后，PNG 图片就不再是运行时的依赖。
标志.py 本身已经包含了全部图像信息。

二、从 PNG 到终端标志的原理

终端本身不能直接显示 PNG 图片。
但是终端支持 ANSI 转义序列。

ANSI 转义序列可以控制终端的前景色和背景色。
例如：
\\x1b[48;2;230;160;0m

这条序列表示：
把背景色设置为 RGB 颜色 230 160 0。

转换脚本会读取 PNG 图片的每一个像素。
然后根据像素的 RGBA 值生成对应的 ANSI 转义序列。
最终把这些序列拼成一个长字符串。

终端打印这个字符串时，
就会把 ANSI 序列解析成颜色，
从而在终端上显示出彩色像素标志。

三、为什么需要转换脚本

因为 PNG 是位图，不是文本。
终端不认识 PNG 文件。

必须有一个程序完成以下工作：
1. 打开 PNG 图片
2. 读取每个像素的 RGBA 值
3. 判断透明像素
4. 生成 ANSI 颜色序列
5. 输出为文本字符串

这个程序就是最早的转换脚本。
它使用 Pillow 库读取 PNG 图片。

但是 Pillow 只在转换阶段使用。
标志.py 本身不依赖 Pillow。

四、为什么不用纯 ASCII 字符画

纯 ASCII 字符画只能靠字符形状拼轮廓。
例如用 # @ . 等符号模拟龟壳形状。

缺点很明显：
1. 丢失颜色
2. 丢失像素细节
3. 无法还原原始像素画的质感

不咸山标志需要保留原始 PNG 的颜色和像素结构。
所以不能使用纯 ASCII 字符画。

五、为什么不用终端基础 16 色

终端基础 16 色是最原始的 ANSI 颜色。
例如：
\\033[43m 表示黄色背景
\\033[42m 表示绿色背景

但是基础 16 色只有固定颜色。
无法表示原始 PNG 里的精细 RGB 颜色。
例如龟壳的暖黄色和绿色身体的过渡色。

所以最终使用了 24 位 TrueColor ANSI 序列。
TrueColor 可以精确表示任意 RGB 颜色。

六、半块字符的作用

终端字符默认是长方形。
如果直接用两个空格表示一个像素，
图像会被横向和纵向拉伸变形。

为了解决这个问题，
使用了半块字符：
▀ 表示上半块
▄ 表示下半块

一个字符位可以同时承载上下两个像素。
这样宽高比例才能恢复到接近 1:1。

这就是为什么标志.py 里会出现 ▀ 和 ▄。

七、透明背景的处理

原始 PNG 图片有透明背景。
转换时不能把透明部分也变成颜色块。

脚本使用透明度阈值判断：
a < 50 表示透明
a >= 50 表示不透明

透明像素输出为空格。
不透明像素才输出 ANSI 颜色块。
这样标志边缘才干净。

八、为什么会出现缝隙

早期使用半块字符时，
终端字体行高会导致上下字符行之间有微小空隙。
看起来像黑色细线。

这不是代码错误，
而是终端字体渲染的固有特性。

后来通过调整字符和颜色方案，
最终确定了现在标志.py 里的显示方式。

九、为什么缩放会导致标志消失

Termux 手势缩放字体时，
会改变终端的行列数。
终端会重置屏幕缓冲区。
之前打印的静态文字会被清掉。

这不是标志.py 的问题，
而是终端显示机制的问题。

早期尝试过用 SIGWINCH 信号捕获缩放事件，
让 Python 在缩放后自动重绘标志。
这个方案有效，但增加了复杂度。

最终为了保持简单和零依赖，
没有把 SIGWINCH 逻辑作为强制要求。
标志.py 保留的是基础显示能力。

十、为什么最终是零依赖

标志.py 最终只使用 Python 标准库：
import signal
import sys

不使用 Pillow。
不读取 PNG 文件。
不依赖任何外部路径。

因为所有图像信息已经固化在 TURTLE_LOGO 字符串里。
这个字符串是转换完成后直接写死在代码里的。

所以标志.py 可以复制到任何地方运行。
不需要安装任何第三方库。

十一、以后的修改方式

如果以后要修改标志，不建议手改字符串。

正确做法是：
1. 准备一张新的 PNG 像素图片
2. 使用 Pillow 写一个临时转换脚本
3. 把 PNG 转换成 ANSI 字符串
4. 替换标志.py 里的 TURTLE_LOGO
5. 删除临时转换脚本和 PNG 依赖
6. 再次确认标志.py 零依赖

手改 ANSI 字符串非常容易出错。
不要直接编辑 TURTLE_LOGO。

十二、原始生成脚本的意义

从聊天记录可以看出，
最初的 logo.py 经过了很多次迭代：
1. 半块字符 RGB 真彩色版
2. 纯背景色双空格版
3. 缩放重绘版
4. 禁自动折行版
5. 零依赖固化版

这些迭代解决的主要问题是：
比例变形
边缘缝隙
缩放消失
外部依赖

最终保留下来的版本是：
零依赖
纯 ANSI 字符串
半块字符
TrueColor
不依赖 PNG
不依赖 Pillow

这就是不咸山标志的完整技术来源。
"""

print(标志技术说明)
